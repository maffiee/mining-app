import { Injectable, inject } from '@angular/core';
import { Firestore, collection, collectionData, getDocs, getDoc, addDoc, serverTimestamp, deleteDoc, doc, updateDoc } from '@angular/fire/firestore';
import { Observable } from 'rxjs';
import { map } from 'rxjs/operators';
import { AuditLogService } from '../../core/services/audit-log.service';

export type ExpenseCategory = 'transport' | 'customer_payment' | 'diesel' | 'labor' | 'other';

export interface CompanyExpense {
  id?: string;
  category: ExpenseCategory;
  amount: number;
  description: string;
  expenseDate: string;
  relatedSaleId?: string;
  relatedPaymentId?: string;
  createdAt?: any;
}

@Injectable({ providedIn: 'root' })
export class CompanyExpenseService {
  private readonly firestore = inject(Firestore);
  private readonly col = collection(this.firestore, 'companyExpenses');
  private readonly salesCol = collection(this.firestore, 'mineralSales');
  private readonly paymentsCol = collection(this.firestore, 'customerPayments'); // check your name is customerPayments
  private readonly auditLogService = inject(AuditLogService);

  private normalizeAmount(value: unknown): number {
    if (value === null || value === undefined || value === '') return 0;

    const parsed = typeof value === 'string'
      ? Number(String(value).replace(/[^0-9.-]/g, ''))
      : Number(value);

    return Number.isFinite(parsed) ? parsed : 0;
  }

  getAll(): Observable<CompanyExpense[]> {
    return collectionData(this.col, { idField: 'id' }) as Observable<CompanyExpense[]>;
  }

  getTotal(): Observable<number> {
    return this.getAll().pipe(
      map(exs => exs.reduce((sum, r) => sum + this.normalizeAmount(r.amount), 0))
    );
  }

  // ONE-TIME FIX - backfill transport + customer payments without deleting manual expenses
  async recalculateAll(): Promise<void> {
    const salesSnap = await getDocs(this.salesCol);
    const paySnap = await getDocs(this.paymentsCol);
    const expenseSnap = await getDocs(this.col);

    for (const d of expenseSnap.docs) {
      const data = d.data() as any;
      const isAutoGenerated = data.category === 'transport' || data.category === 'customer_payment';
      if (isAutoGenerated) {
        await deleteDoc(doc(this.firestore, 'companyExpenses', d.id));
      }
    }

    for (const s of salesSnap.docs) {
      const sale: any = s.data();
      const transportCost = this.normalizeAmount(sale.transportationCost);
      if (transportCost > 0) {
        await addDoc(this.col, {
          category: 'transport',
          amount: transportCost,
          description: `Transport to ${sale.buyerLocation} for ${sale.buyerName} - ${sale.quantity}kg ${sale.mineralType}`,
          expenseDate: sale.saleDate,
          relatedSaleId: s.id,
          createdAt: serverTimestamp(),
        });
      }
    }

    for (const p of paySnap.docs) {
      const pay: any = p.data();
      const amount = this.normalizeAmount(pay.amountPaid ?? pay.amount ?? 0);
      if (amount > 0) {
        await addDoc(this.col, {
          category: 'customer_payment',
          amount,
          description: `Payment to ${pay.customerName || 'customer'} - Settlement ${pay.settlementId || ''}`,
          expenseDate: pay.paymentDate || pay.createdAt || new Date().toISOString(),
          relatedPaymentId: p.id,
          createdAt: serverTimestamp(),
        });
      }
    }
  }

  async create(expense: Omit<CompanyExpense, 'id'>): Promise<void> {
    const normalizedExpense = {
      ...expense,
      amount: this.normalizeAmount(expense.amount),
      expenseDate: expense.expenseDate || new Date().toISOString().split('T')[0],
    };

    const docRef = await addDoc(this.col, {
      ...normalizedExpense,
      createdAt: serverTimestamp(),
    });

    await this.auditLogService.log({
      action: 'CREATE',
      collection: 'companyExpenses',
      recordId: docRef.id,
      description: `Created expense of ₦${normalizedExpense.amount} for ${normalizedExpense.category} - ${normalizedExpense.description}`
    });
  }

  async update(id: string, data: Partial<CompanyExpense>): Promise<void> {
    const docRef = doc(this.firestore, 'companyExpenses', id);
    const oldSnap = await getDoc(docRef);
    const oldData = oldSnap.exists() ? oldSnap.data() as any : null;
    const normalizedData = {
      ...data,
      ...(data.amount !== undefined ? { amount: this.normalizeAmount(data.amount) } : {}),
      updatedAt: serverTimestamp(),
    };

    await updateDoc(docRef, normalizedData);

    await this.auditLogService.log({
      action: 'UPDATE',
      collection: 'companyExpenses',
      recordId: id,
      description: `Updated expense from ₦${this.normalizeAmount(oldData?.amount ?? 0)} to ₦${this.normalizeAmount((data as any).amount ?? oldData?.amount ?? 0)}`,
      before: oldData,
      after: normalizedData,
    });
  }

  async delete(id: string): Promise<void> {
    const docRef = doc(this.firestore, 'companyExpenses', id);
    const oldSnap = await getDoc(docRef);
    const oldData = oldSnap.exists() ? oldSnap.data() as any : null;

    await deleteDoc(docRef);

    await this.auditLogService.log({
      action: 'DELETE',
      collection: 'companyExpenses',
      recordId: id,
      description: `Deleted expense of ₦${oldData?.amount} for ${oldData?.category} - ${oldData?.description}`,
      before: oldData,
    });
  }

}